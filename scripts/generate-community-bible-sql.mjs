// Compile the committed static catalogue into table-free PostgreSQL validators.
// No fetching or seed rows. Review generated migrations before deploying them.
import assert from "node:assert/strict";
import { readFile, writeFile } from "node:fs/promises";
import { pathToFileURL } from "node:url";

const initialURL = new URL(
  "../supabase/migrations/20261016041414_add_church_community.sql",
  import.meta.url,
);
const upgradeURL = new URL(
  "../supabase/migrations/20261020040857_use_static_community_bible_catalog.sql",
  import.meta.url,
);
const begin = "-- BEGIN STATIC BIBLE VALIDATORS";
const end = "-- END STATIC BIBLE VALIDATORS";
const quote = (value) => `'${value.replaceAll("'", "''")}'`;

export function renderBibleValidators(books, catalogue) {
  const versions = ["ko-krv", "en-kjv", "de-luther1912"];
  const chapters = new Map(catalogue.chapters.map((row) => [
    `${row.version}:${row.book}:${row.chapter}`,
    row.verses,
  ]));
  assert.equal(chapters.size, catalogue.chapters.length);
  assert.equal(
    chapters.size,
    books.reduce((n, b) => n + b.maxChapter, 0) * versions.length,
  );
  const editions = versions.map((version) => {
    const byBook = books.map((book) => {
      const counts = Array.from({ length: book.maxChapter }, (_, index) => {
        const verses = chapters.get(`${version}:${book.bookCode}:${index + 1}`);
        assert.ok(
          verses?.length,
          `Missing chapter: ${version}/${book.bookCode}/${index + 1}`,
        );
        assert.ok(
          verses.every((v, i) =>
            Number.isSafeInteger(v) && v > 0 && (!i || v > verses[i - 1])
          ),
        );
        // Compact continuous chapters; keep exact IDs if an edition has gaps.
        return verses.every((verse, i) => verse === i + 1)
          ? verses.length
          : verses;
      });
      return `  ${JSON.stringify(book.bookCode)}:${JSON.stringify(counts)}`;
    });
    const value = `{\n${byBook.join(",\n")}\n}`;
    return `when ${quote(version)} then $catalog$${value}$catalog$::jsonb`;
  });
  return `${begin}
-- Generated from domain/community/{books,bible-catalog}.json.
-- Static function constants only: no reference tables or seed INSERTs.
create or replace function church_community_private.bible_book(p_book text)
returns integer[] language sql immutable set search_path='' as $$
  select case p_book
${
    books.map((b) =>
      `    when ${quote(b.bookCode)} then array[${b.bookSeq},${b.maxChapter}]`
    ).join("\n")
  }
    else null::integer[] end
$$;

create or replace function church_community_private.bible_verse_ids(p_version text,p_book text,p_chapter integer)
returns integer[] language plpgsql immutable set search_path='' as $$
declare chapter_data jsonb;
begin
  if p_chapter is null or p_chapter < 1 then return '{}'::integer[]; end if;
  chapter_data := (case p_version
${editions.join("\n")}
    else '{}'::jsonb end)->p_book->(p_chapter-1);
  if jsonb_typeof(chapter_data)='number' then
    return array(select generate_series(1,chapter_data::integer));
  elsif jsonb_typeof(chapter_data)='array' then
    return array(select value::integer from jsonb_array_elements_text(chapter_data));
  end if;
  return '{}'::integer[];
end $$;

create or replace function church_community_private.bible_valid_verse(p_version text,p_book text,p_chapter integer,p_verse integer)
returns boolean language sql immutable set search_path='' as $$
  select coalesce(p_verse=any(church_community_private.bible_verse_ids(p_version,p_book,p_chapter)),false)
$$;
${end}`;
}

export async function generateBibleSql({ check = false } = {}) {
  const books = JSON.parse(
    await readFile(
      new URL("../domain/community/books.json", import.meta.url),
      "utf8",
    ),
  );
  const catalogue = JSON.parse(
    await readFile(
      new URL("../domain/community/bible-catalog.json", import.meta.url),
      "utf8",
    ),
  );
  const validators = renderBibleValidators(books, catalogue);
  const initial = await readFile(initialURL, "utf8");
  assert.ok(
    initial.includes(begin) && initial.includes(end),
    "Missing validator markers",
  );
  const updated = initial.replace(
    new RegExp(`${begin}[\\s\\S]*?${end}`),
    () => validators,
  );
  const functions = ["post_json", "comment_json", "api"].map((name) => {
    const source = updated.match(
      new RegExp(
        `create function church_community_private\\.${name}\\([\\s\\S]*?\\n(?:end )?\\$\\$;`,
      ),
    )?.[0];
    assert.ok(source, `Missing function: ${name}`);
    return source.replace("create function", "create or replace function");
  });
  const upgrade = `-- Generated by scripts/generate-community-bible-sql.mjs.
-- Supports both the original seeded migration and new table-free installs.
-- User-authored posts, ranges and meditation references are preserved.
begin;
${validators}

${functions.join("\n\n")}

-- Replace reference-table FKs with checks against the same static catalogue.
do $$ declare fk record; begin
  for fk in select conrelid::regclass as relation,conname from pg_constraint
    where contype='f' and confrelid in (
      to_regclass('church_community_private.bible_reference_books'),
      to_regclass('church_community_private.bible_reference_verses'))
      and conrelid in ('public.church_post_reading_ranges'::regclass,
        'public.church_comment_meditation_verses'::regclass)
  loop
    execute format('alter table %s drop constraint %I',fk.relation,fk.conname);
  end loop;
end $$;
alter table public.church_post_reading_ranges
  drop constraint if exists church_reading_range_reference;
alter table public.church_post_reading_ranges add constraint church_reading_range_reference
  check(chapter_end<=coalesce((church_community_private.bible_book(book_code))[2],0));
alter table public.church_comment_meditation_verses
  drop constraint if exists church_meditation_verse_reference_check;
alter table public.church_comment_meditation_verses add constraint church_meditation_verse_reference_check
  check(church_community_private.bible_valid_verse(bible_version,book_code,chapter,verse));

drop table if exists church_community_private.bible_reference_verses;
drop table if exists church_community_private.bible_reference_books;
revoke all on function church_community_private.bible_book(text),
  church_community_private.bible_verse_ids(text,text,integer),
  church_community_private.bible_valid_verse(text,text,integer,integer)
  from public,anon,authenticated;
commit;
`;
  for (const [url, content] of [[initialURL, updated], [upgradeURL, upgrade]]) {
    if (check) {
      assert.equal(
        await readFile(url, "utf8"),
        content,
        `Stale generated SQL: ${url.pathname}`,
      );
    } else await writeFile(url, content);
  }
}

if (
  process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href
) {
  await generateBibleSql({ check: process.argv.includes("--check") });
  console.log("Static Bible SQL validators are up to date.");
}
